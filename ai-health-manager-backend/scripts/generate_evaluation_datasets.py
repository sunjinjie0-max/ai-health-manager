def classify_intent(query: str) -> str:
    lowered = query.lower()
    for intent, keywords in INTENT_KEYWORDS:
        if any(keyword in lowered for keyword in keywords):
            return intent
    return "general_health"


def task_agents(query: str) -> list[str]:
    lowered = query.lower()
    intent = classify_intent(query)
    agents: list[str] = []
    if any(keyword in lowered for keyword in NUTRITION_KEYWORDS) or intent == "nutrition":
        agents.append("nutrition")
    if any(keyword in lowered for keyword in ENVIRONMENT_KEYWORDS) or intent == "environment":
        agents.append("environment")
    if any(keyword in lowered for keyword in EXERCISE_KEYWORDS) or intent == "exercise":
        agents.append("exercise")
    return agents


def expected(query: str, **overrides: Any) -> dict[str, Any]:
    result: dict[str, Any] = {
        "intent": classify_intent(query),
        "urgent": any(keyword in query.lower() for keyword in URGENT_KEYWORDS),
        "prompt_injection": False,
        "task_agents": task_agents(query),
    }
    result.update(overrides)
    return result


def case(
    case_id: str,
    query: str,
    tags: list[str],
    *,
    response: str = "",
    expected_overrides: dict[str, Any] | None = None,
    setup: dict[str, Any] | None = None,
    profile: dict[str, Any] | None = None,
    retrieved_docs: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "id": f"{GENERATED_PREFIX}{case_id}",
        "query": query,
        "tags": tags,
        "expected": expected(query, **(expected_overrides or {})),
    }
    if response:
        payload["reference_response"] = response
    if setup:
        payload["setup"] = setup
    if profile:
        payload["profile"] = profile
    if retrieved_docs:
        payload["retrieved_docs"] = retrieved_docs
    return payload


