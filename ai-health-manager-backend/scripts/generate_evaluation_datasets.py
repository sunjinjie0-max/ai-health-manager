def write_dataset(suite: str) -> int:
    path = DATASET_DIR / f"{suite}_cases.json"
    original = json.loads(path.read_text(encoding="utf-8"))
    seed_cases = [item for item in original if not str(item.get("id", "")).startswith(GENERATED_PREFIX)]
    target = TARGET_COUNTS[suite]
    needed = target - len(seed_cases)
    if needed < 0:
        raise ValueError(f"{suite} has {len(seed_cases)} seed cases, exceeding target {target}")

    candidates = BUILDERS[suite]()
    if len(candidates) < needed:
        raise ValueError(f"{suite} only generated {len(candidates)} candidates, needs {needed}")

    dataset = seed_cases + candidates[:needed]
    path.write_text(json.dumps(dataset, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return len(dataset)


def main() -> None:
    counts = {suite: write_dataset(suite) for suite in TARGET_COUNTS}
    total = sum(counts.values())
    if total != 240:
        raise AssertionError(f"Expected 240 cases, generated {total}")
    print(json.dumps({"counts": counts, "total": total}, ensure_ascii=False))


if __name__ == "__main__":
    main()
